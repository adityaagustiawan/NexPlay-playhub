-- Enable Supabase Realtime for public.games so a Nexstudio publish/update
-- propagates to players with the game open (live version refresh).
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'games'
  ) then
    alter publication supabase_realtime add table public.games;
  end if;
end $$;
